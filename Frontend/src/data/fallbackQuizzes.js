function choice(id, label) {
  return { id, label }
}

function item(id, label) {
  return { id, label }
}

function pair(leftId, rightId) {
  return { leftId, rightId }
}

function singleChoice(id, label, difficulty, explanation, choices, correctChoiceId) {
  return {
    id,
    label,
    type: 'QCM_SINGLE',
    difficulty,
    points: 0,
    explanation,
    choices,
    correctChoiceIds: [correctChoiceId],
    leftItems: [],
    rightItems: [],
    correctPairs: [],
    orderingItems: [],
    correctOrder: [],
  }
}

function trueFalse(id, label, difficulty, explanation, correct) {
  return {
    id,
    label,
    type: 'TRUE_FALSE',
    difficulty,
    points: 0,
    explanation,
    choices: [choice('true', 'Vrai'), choice('false', 'Faux')],
    correctChoiceIds: [correct ? 'true' : 'false'],
    leftItems: [],
    rightItems: [],
    correctPairs: [],
    orderingItems: [],
    correctOrder: [],
  }
}

function matching(id, label, difficulty, explanation, leftItems, rightItems, correctPairs) {
  return {
    id,
    label,
    type: 'MATCHING',
    difficulty,
    points: 0,
    explanation,
    choices: [],
    correctChoiceIds: [],
    leftItems,
    rightItems,
    correctPairs,
    orderingItems: [],
    correctOrder: [],
  }
}

function ordering(id, label, difficulty, explanation, orderingItems, correctOrder) {
  return {
    id,
    label,
    type: 'ORDERING',
    difficulty,
    points: 0,
    explanation,
    choices: [],
    correctChoiceIds: [],
    leftItems: [],
    rightItems: [],
    correctPairs: [],
    orderingItems,
    correctOrder,
  }
}

